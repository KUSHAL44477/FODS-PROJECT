"""
pages/2_Data_Workspace.py
Data Workspace for OceanWatch.
Provides CSV file upload, automated validation audit, interactive cleaning studio,
before-and-after quality metric comparisons, and cleaned data export.
"""

import io
from pathlib import Path
import streamlit as st
import pandas as pd

from src.ingestion import load_csv, load_sample, build_metadata
from src.validation import validate_dataset
from src.cleaning import clean_dataset, get_quality_comparison
from src.database import log_analysis_run

st.set_page_config(page_title="OceanWatch | Data Workspace", page_icon="🧹", layout="wide")

# Ensure session state initialization
if "raw_df" not in st.session_state:
    st.session_state["raw_df"] = None
if "active_df" not in st.session_state:
    st.session_state["active_df"] = None
if "metadata" not in st.session_state:
    st.session_state["metadata"] = None
if "cleaning_log" not in st.session_state:
    st.session_state["cleaning_log"] = []
if "cleaned_preview_df" not in st.session_state:
    st.session_state["cleaned_preview_df"] = None
if "cleaning_comparison" not in st.session_state:
    st.session_state["cleaning_comparison"] = None

st.title("🧹 Data Workspace & Quality Assurance")
st.markdown("Upload or load oceanographic measurements, audit data integrity, apply documented cleaning strategies, and inspect before/after comparisons.")

# Section 1: Ingestion & Upload
st.markdown("---")
st.subheader("1. Ingestion & Dataset Selection")

u_col1, u_col2 = st.columns([2, 1], gap="medium")

with u_col1:
    uploaded_file = st.file_uploader(
        "Upload Ocean CSV Dataset",
        type=["csv"],
        help="Upload a CSV with ocean observation variables (e.g., temperature, salinity, oxygen, depth).",
    )
    if uploaded_file is not None:
        try:
            df_up = load_csv(uploaded_file)
            meta_up = build_metadata(
                df=df_up,
                source_name=f"User Upload: {uploaded_file.name}",
                is_synthetic=False,
            )
            st.session_state["raw_df"] = df_up.copy(deep=True)
            st.session_state["active_df"] = df_up.copy(deep=True)
            st.session_state["metadata"] = meta_up
            st.session_state["cleaning_log"] = []
            st.session_state["cleaned_preview_df"] = None
            st.session_state["cleaning_comparison"] = None
            st.success(f"Successfully loaded '{uploaded_file.name}' ({len(df_up):,} rows).")
        except Exception as ex:
            st.error(f"Error loading uploaded file: {ex}")

with u_col2:
    st.markdown("**Benchmark Dataset**")
    st.caption("Don't have a CSV? Load the 3,000+ row synthetic benchmark containing realistic physical profiles.")
    if st.button("📥 Load Sample Ocean Dataset", key="workspace_load_sample", use_container_width=True):
        with st.spinner("Loading synthetic sample data..."):
            df_sample, meta_sample = load_sample("data/raw/sample_ocean.csv")
            st.session_state["raw_df"] = df_sample.copy(deep=True)
            st.session_state["active_df"] = df_sample.copy(deep=True)
            st.session_state["metadata"] = meta_sample
            st.session_state["cleaning_log"] = []
            st.session_state["cleaned_preview_df"] = None
            st.session_state["cleaning_comparison"] = None
        st.success("Loaded synthetic ocean sample dataset.")

# Verify data availability
if st.session_state["raw_df"] is None:
    st.warning("⚠️ No dataset loaded yet. Upload a CSV file above or click 'Load Sample Ocean Dataset' to begin.")
    st.stop()

raw_df = st.session_state["raw_df"]
meta = st.session_state["metadata"]

# Synthetic data banner
if meta and meta.get("is_synthetic"):
    st.info(
        "🏷️ **ACTIVE: SYNTHETIC SAMPLE DATA** — Generated by `scripts/make_sample_data.py`. "
        "Intentionally contains ~5% missing values, duplicate rows, and outlier measurements for testing."
    )

# Section 2: Raw Data Preview & Metadata
st.markdown("---")
st.subheader("2. Dataset Preview & Data Types")

meta_col1, meta_col2, meta_col3, meta_col4 = st.columns(4)
meta_col1.metric("Rows", f"{len(raw_df):,}")
meta_col2.metric("Columns", f"{len(raw_df.columns)}")
meta_col3.metric("Source", meta.get("source_name", "Unknown")[:25])
meta_col4.metric("Reference Period", meta.get("reference_period", "Climatology")[:25])

with st.expander("🔍 View Raw Data Table (First 15 Rows)", expanded=False):
    st.dataframe(raw_df.head(15), use_container_width=True)

# Section 3: Data Quality & Validation Audit
st.markdown("---")
st.subheader("3. Comprehensive Data Validation Audit")

val_report = validate_dataset(raw_df)

val_c1, val_c2, val_c3 = st.columns(3)
val_c1.metric("Total Missing Cells", f"{val_report['total_missing_cells']:,}", f"{val_report['overall_missing_pct']}% of data")
val_c2.metric("Duplicate Rows", f"{val_report['duplicate_rows_count']:,}")
total_violations = sum(v["count"] for v in val_report["range_violations"].values())
val_c3.metric("Physical Range Violations", f"{total_violations:,}")

# Missingness & Types Breakdown
t_col1, t_col2 = st.columns([1.5, 1], gap="medium")

with t_col1:
    st.markdown("##### Missing Values & Data Types per Column")
    report_rows = []
    for col in raw_df.columns:
        report_rows.append({
            "Column": col,
            "Data Type": str(raw_df[col].dtype),
            "Missing Count": val_report["missing_counts"].get(col, 0),
            "Missing %": val_report["missing_percentages"].get(col, 0.0),
            "Range Status": "⚠️ Violations" if col in val_report["range_violations"] else "✅ OK",
        })
    st.dataframe(pd.DataFrame(report_rows), hide_index=True, use_container_width=True)

with t_col2:
    st.markdown("##### Marine Physical Range Violations")
    if val_report["range_violations"]:
        viols_data = []
        for col, info in val_report["range_violations"].items():
            viols_data.append({
                "Indicator": col,
                "Count": info["count"],
                "Allowed Bounds": f"[{info['allowed_min']}, {info['allowed_max']}]",
                "Extreme Values": f"min {info['observed_min']} / max {info['observed_max']}",
            })
        st.dataframe(pd.DataFrame(viols_data), hide_index=True, use_container_width=True)
    else:
        st.success("All observed indicator values fall within theoretical ocean physical limits.")

    if val_report["impossible_values"]:
        st.markdown("##### 🚨 Physically Impossible Ocean Values")
        for col, issues in val_report["impossible_values"].items():
            for iss in issues:
                st.error(f"**{col}**: {iss['issue']} ({iss['count']} occurrences)")

if val_report["suspicious_row_indices"]:
    with st.expander(f"⚠️ Inspect Suspicious Rows ({len(val_report['suspicious_row_indices']):,} rows flagged)", expanded=False):
        sample_indices = val_report["suspicious_row_indices"][:20]
        st.caption("Displaying sample of up to 20 suspicious rows flagged for range or impossible value anomalies:")
        st.dataframe(raw_df.loc[sample_indices], use_container_width=True)

# Section 4: Interactive Cleaning Studio
st.markdown("---")
st.subheader("4. Interactive Cleaning Studio")
st.markdown(
    """
    Configure and test cleaning strategies below. All transformations operate on an isolated copy
    so your raw dataset is never permanently mutated without confirmation.
    """
)

clean_c1, clean_c2 = st.columns(2, gap="medium")

with clean_c1:
    dedup_choice = st.checkbox("Remove Exact Duplicate Rows", value=True)
    
    missing_strategy_options = {
        "leave_as_is": "Leave missing values as-is (DEFAULT)",
        "drop_rows": "Drop rows with missing values",
        "fill_mean": "Impute missing with column mean",
        "fill_median": "Impute missing with column median",
        "fill_group_median": "Impute missing with group-wise median (by Region)",
        "interpolate_linear": "Isolated linear interpolation (within Region group)",
    }
    
    selected_strategy_key = st.selectbox(
        "Select Missing Value Treatment Strategy",
        options=list(missing_strategy_options.keys()),
        format_func=lambda k: missing_strategy_options[k],
        index=0,
    )

with clean_c2:
    all_numeric = val_report["numeric_columns"]
    target_cols = st.multiselect(
        "Target Numeric Columns for Treatment",
        options=all_numeric,
        default=all_numeric,
        help="Select which numeric columns to apply missingness strategies to.",
    )
    
    group_col = None
    if selected_strategy_key in ["fill_group_median", "interpolate_linear"]:
        cat_cols = val_report["non_numeric_columns"]
        default_group_idx = cat_cols.index("region") if "region" in cat_cols else 0
        group_col = st.selectbox(
            "Grouping Column",
            options=cat_cols,
            index=default_group_idx if cat_cols else 0,
        )

# Apply Cleaning button
if st.button("⚡ Apply Cleaning Strategy & Preview Comparison", type="primary"):
    with st.spinner("Processing cleaning transformations on dataset copy..."):
        cleaned_df, cleaning_log = clean_dataset(
            df=raw_df,
            remove_duplicates=dedup_choice,
            missing_strategy=selected_strategy_key,
            target_columns=target_cols if target_cols else None,
            group_col=group_col,
        )
        comparison = get_quality_comparison(raw_df, cleaned_df)
        st.session_state["cleaned_preview_df"] = cleaned_df
        st.session_state["cleaning_log"] = cleaning_log
        st.session_state["cleaning_comparison"] = comparison

    st.success("Cleaning operations completed. Review the before/after audit below.")

# Section 5: Before / After Comparison Audit
if st.session_state["cleaned_preview_df"] is not None:
    cleaned_df = st.session_state["cleaned_preview_df"]
    log = st.session_state["cleaning_log"]
    comp = st.session_state["cleaning_comparison"]

    st.markdown("---")
    st.subheader("5. Before & After Quality Comparison")

    # High-level metrics
    cmp1, cmp2, cmp3 = st.columns(3)
    cmp1.metric("Rows", f"{comp['clean_rows']:,}", f"{comp['clean_rows'] - comp['raw_rows']:,} rows")
    cmp2.metric("Missing %", f"{comp['clean_missing_pct']}%", f"{comp['clean_missing_pct'] - comp['raw_missing_pct']:.2f}%")
    cmp3.metric("Duplicate Rows", f"{comp['clean_duplicates']:,}", f"{comp['clean_duplicates'] - comp['raw_duplicates']:,}")

    # Transformation Log
    st.markdown("##### Transformation Audit Log")
    log_rows = []
    for step in log:
        log_rows.append({
            "Step": step["step"],
            "Description": step["description"],
            "Rows / Cells Affected": step["rows_affected"],
        })
    st.dataframe(pd.DataFrame(log_rows), hide_index=True, use_container_width=True)

    # Variable-level summary statistics comparison
    st.markdown("##### Numeric Indicators: Pre vs Post Summary Statistics")
    var_rows = []
    for var, s in comp["variables"].items():
        var_rows.append({
            "Indicator": var,
            "Raw Count": s["raw_count"],
            "Clean Count": s["clean_count"],
            "Raw Mean": s["raw_mean"],
            "Clean Mean": s["clean_mean"],
            "Raw Std": s["raw_std"],
            "Clean Std": s["clean_std"],
            "Raw Median": s["raw_median"],
            "Clean Median": s["clean_median"],
        })
    st.dataframe(pd.DataFrame(var_rows), hide_index=True, use_container_width=True)

    # Action buttons: Save as Active or Download CSV
    st.markdown("---")
    st.subheader("6. Commit & Export Cleaned Dataset")
    
    act_c1, act_c2 = st.columns(2)
    
    with act_c1:
        if st.button("💾 Set Cleaned Data as Active Session Dataset", use_container_width=True):
            st.session_state["active_df"] = cleaned_df.copy(deep=True)
            # Log to SQLite
            try:
                log_analysis_run(
                    algorithm=f"Data Cleaning ({selected_strategy_key})",
                    summary_dict={
                        "raw_rows": comp["raw_rows"],
                        "clean_rows": comp["clean_rows"],
                        "raw_missing_pct": comp["raw_missing_pct"],
                        "clean_missing_pct": comp["clean_missing_pct"],
                    },
                    cleaning_config_dict={
                        "remove_duplicates": dedup_choice,
                        "missing_strategy": selected_strategy_key,
                        "target_columns": target_cols,
                    },
                )
            except Exception as e:
                pass
            st.success("Cleaned dataset is now active across all OceanWatch analytical pages!")

    with act_c2:
        # Convert to CSV buffer for download
        csv_buffer = io.StringIO()
        cleaned_df.to_csv(csv_buffer, index=False)
        st.download_button(
            label="📥 Download Cleaned CSV",
            data=csv_buffer.getvalue().encode("utf-8"),
            file_name="oceanwatch_cleaned_data.csv",
            mime="text/csv",
            use_container_width=True,
        )
